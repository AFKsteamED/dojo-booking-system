export type DictKey = keyof typeof dict.zh;

export function t(locale: Locale, key: DictKey, vars?: Vars): string {
  const table = (dict[locale] ?? dict.zh) as Record<string, string>;
  let template = table[key] ?? (dict.zh as Record<string, string>)[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}

export function hasKey(key: string): key is DictKey {
  return key in dict.zh;
}

export function isLocale(v: unknown): v is Locale {
  return v === "zh" || v === "en";
}

/** LINE App / 瀏覽器語言 → 我們的 locale（中文系統用中文，其餘用英文） */
export function localeFromLanguage(lang: string | null | undefined): Locale {
  return lang && lang.toLowerCase().startsWith("zh") ? "zh" : "en";
}
